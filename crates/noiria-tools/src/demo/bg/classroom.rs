//! 夕方の教室。一点透視の箱（奥壁・左壁・右壁・床・天井）に、左壁の窓から西日が差す。
//! 光は左から。立ち絵は中央〜下部に重なるので、細部は両端と奥壁に寄せる。

use super::*;

const BW: (f32, f32, f32, f32) = (400.0, 170.0, 940.0, 420.0);

/// 左壁上の点: u = 0（手前）..1（奥壁）, v = 0（上）..1（下）。
fn lw(u: f32, v: f32) -> P {
    let (x, top, bot) = (BW.0 * u, BW.1 * u, 720.0 - 300.0 * u);
    (x, top + (bot - top) * v)
}

/// 床上の点: s = 0（左）..1（右）, t = 0（手前）..1（奥）。
fn fl(s: f32, t: f32) -> P {
    let l = (BW.0 * t, 720.0 - 300.0 * t);
    let r = (1280.0 - 340.0 * t, 720.0 - 300.0 * t);
    (l.0 + (r.0 - l.0) * s, l.1)
}

fn desk(cv: &mut Canvas, cx: f32, y: f32, w: f32) {
    let h = w * 0.28;
    let top = col(214, 164, 116);
    let side = col(168, 122, 86);
    let leg = col(112, 88, 80);
    for dx in [-0.42, 0.42] {
        bar(
            cv,
            (cx + dx * w, y + h),
            (cx + dx * w, y + h + w * 0.5),
            w * 0.05,
            leg,
        );
    }
    poly(
        cv,
        &[
            (cx - w * 0.42, y),
            (cx + w * 0.42, y),
            (cx + w * 0.5, y + h),
            (cx - w * 0.5, y + h),
        ],
        top,
    );
    rect(cv, cx - w * 0.5, y + h, w, w * 0.07, side);
}

pub fn draw() -> Canvas {
    let mut cv = canvas();
    // 壁・床・天井
    rect(&mut cv, 0.0, 0.0, 1280.0, 720.0, col(244, 226, 204));
    poly(
        &mut cv,
        &[(0.0, 0.0), (1280.0, 0.0), (BW.2, BW.1), (BW.0, BW.1)],
        col(238, 222, 208),
    );
    poly(
        &mut cv,
        &[(0.0, 0.0), (BW.0, BW.1), (BW.0, BW.3), (0.0, 720.0)],
        col(240, 210, 180),
    );
    poly(
        &mut cv,
        &[(1280.0, 0.0), (BW.2, BW.1), (BW.2, BW.3), (1280.0, 720.0)],
        col(222, 196, 172),
    );
    poly(
        &mut cv,
        &[(0.0, 720.0), (1280.0, 720.0), (BW.2, BW.3), (BW.0, BW.3)],
        col(206, 158, 112),
    );
    // 床板の線（5 本）
    for i in 1..6 {
        let s = i as f32 / 6.0;
        bar(&mut cv, fl(s, 0.0), fl(s, 1.0), 2.5, col(194, 146, 102));
    }
    // 左壁の窓（3 連）と西日の空
    let frame = col(250, 240, 226);
    poly(
        &mut cv,
        &[lw(0.05, 0.2), lw(0.95, 0.2), lw(0.95, 0.66), lw(0.05, 0.66)],
        frame,
    );
    for (u0, u1) in [(0.08, 0.34), (0.38, 0.65), (0.69, 0.92)] {
        let m = pmask(
            &cv,
            &[lw(u0, 0.24), lw(u1, 0.24), lw(u1, 0.62), lw(u0, 0.62)],
        );
        vgrad_in(
            &mut cv,
            &m,
            100.0,
            520.0,
            col(255, 196, 144),
            col(255, 224, 170),
        );
        // 窓の外の街（1 色のシルエット）
        poly(
            &mut cv,
            &[
                lw(u0, 0.5),
                lw(u0 + (u1 - u0) * 0.3, 0.46),
                lw(u0 + (u1 - u0) * 0.55, 0.52),
                lw(u0 + (u1 - u0) * 0.8, 0.44),
                lw(u1, 0.5),
                lw(u1, 0.62),
                lw(u0, 0.62),
            ],
            cola(226, 156, 140, 1.0),
        );
    }
    // 床に落ちる西日（3 枚の平行四辺形）
    for (i, (a, b)) in [(0.0f32, 0.22f32), (0.26, 0.5), (0.55, 0.82)]
        .into_iter()
        .enumerate()
    {
        let (t0, t1) = (0.04 + 0.12 * i as f32, 0.28 + 0.12 * i as f32);
        poly(
            &mut cv,
            &[
                fl(a, t0),
                fl(a + 0.2, t0),
                fl(a + 0.2 + b * 0.5, t1),
                fl(a + b * 0.5, t1),
            ],
            cola(255, 214, 150, 0.55),
        );
    }
    // 奥壁: 黒板・時計
    rect(&mut cv, 470.0, 214.0, 400.0, 130.0, col(122, 92, 72));
    rect(&mut cv, 480.0, 222.0, 380.0, 114.0, col(72, 108, 94));
    rect(&mut cv, 470.0, 344.0, 400.0, 8.0, col(104, 78, 62));
    for x in [520.0, 600.0, 680.0] {
        bar(
            &mut cv,
            (x, 236.0),
            (x + 46.0, 236.0),
            3.0,
            col(206, 224, 214),
        );
    }
    ell(&mut cv, 670.0, 196.0, 20.0, 20.0, col(252, 248, 238));
    bar(
        &mut cv,
        (670.0, 196.0),
        (670.0, 184.0),
        2.5,
        col(80, 70, 70),
    );
    bar(
        &mut cv,
        (670.0, 196.0),
        (680.0, 200.0),
        2.5,
        col(80, 70, 70),
    );
    // 右壁: 掲示板
    poly(
        &mut cv,
        &[
            (1120.0, 150.0),
            (1220.0, 128.0),
            (1220.0, 330.0),
            (1120.0, 300.0),
        ],
        col(212, 178, 132),
    );
    // 机（左右の端に 2 列ずつ）
    for (cx, y, w) in [
        (60.0, 600.0, 220.0),
        (205.0, 500.0, 130.0),
        (1220.0, 600.0, 220.0),
        (1085.0, 500.0, 130.0),
        (292.0, 450.0, 96.0),
        (990.0, 450.0, 96.0),
    ] {
        desk(&mut cv, cx, y, w);
    }
    cv
}
