//! タイトル背景。左半分は文字が乗るので落ち着いた暗さのまま、右に三日月と小さな丘の望遠鏡。

use super::*;

pub fn draw() -> Canvas {
    let mut cv = canvas();
    vgrad(&mut cv, 0.0, 520.0, col(12, 17, 50), col(52, 62, 120));
    let mut rng = Rng::new(77);
    for _ in 0..9 {
        let (x, y) = (rng.r(20.0, 620.0), rng.r(20.0, 380.0));
        ell(&mut cv, x, y, 1.6, 1.6, cola(226, 232, 252, 0.6));
    }
    for _ in 0..16 {
        let (x, y) = (rng.r(660.0, 1260.0), rng.r(20.0, 380.0));
        ell(
            &mut cv,
            x,
            y,
            rng.r(1.6, 2.6),
            rng.r(1.6, 2.6),
            cola(236, 240, 255, 0.85),
        );
    }
    for (x, y, r) in [
        (760.0, 120.0, 12.0),
        (1150.0, 330.0, 10.0),
        (700.0, 300.0, 9.0),
    ] {
        sparkle(&mut cv, x, y, r, col(250, 250, 255));
    }
    let moon = Mask::from_path(&Path::ellipse(980.0, 200.0, 74.0, 74.0, 0.0), (W, H));
    let cut = Mask::from_path(&Path::ellipse(1018.0, 180.0, 64.0, 64.0, 0.0), (W, H));
    cv.fill_solid(&moon.sub(&cut), col(252, 238, 196));
    poly(
        &mut cv,
        &[
            (0.0, 520.0),
            (240.0, 492.0),
            (520.0, 500.0),
            (800.0, 470.0),
            (1040.0, 452.0),
            (1280.0, 480.0),
            (1280.0, 720.0),
            (0.0, 720.0),
        ],
        col(30, 38, 88),
    );
    poly(
        &mut cv,
        &[
            (0.0, 600.0),
            (300.0, 566.0),
            (640.0, 584.0),
            (900.0, 540.0),
            (1280.0, 556.0),
            (1280.0, 720.0),
            (0.0, 720.0),
        ],
        col(19, 26, 64),
    );
    // 右の丘の天体望遠鏡（シルエット）
    let sil = col(12, 17, 44);
    bar(&mut cv, (1052.0, 470.0), (1010.0, 540.0), 6.0, sil);
    bar(&mut cv, (1052.0, 470.0), (1094.0, 540.0), 6.0, sil);
    bar(&mut cv, (1052.0, 470.0), (1052.0, 540.0), 6.0, sil);
    bar(&mut cv, (1030.0, 476.0), (1104.0, 418.0), 20.0, sil);
    cv
}
