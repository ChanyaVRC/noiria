//! 天文部の部室。奥壁に夜空の窓、左に本棚、右に望遠鏡。光は窓（中央奥）と天井の暖色灯から。

use super::*;

pub fn draw() -> Canvas {
    let mut cv = canvas();
    rect(&mut cv, 0.0, 0.0, 1280.0, 490.0, col(216, 208, 198));
    rect(&mut cv, 0.0, 440.0, 1280.0, 50.0, col(196, 186, 178));
    poly(&mut cv, &[(0.0, 490.0), (1280.0, 490.0), (1280.0, 720.0), (0.0, 720.0)], col(168, 134, 104));
    poly(&mut cv, &[(0.0, 490.0), (1280.0, 490.0), (1280.0, 508.0), (0.0, 508.0)], col(150, 118, 92));
    // 窓: 夜空と 2 つの大きな星
    rect(&mut cv, 480.0, 70.0, 420.0, 300.0, col(246, 240, 230));
    let m = pmask(&cv, &[(494.0, 84.0), (886.0, 84.0), (886.0, 356.0), (494.0, 356.0)]);
    vgrad_in(&mut cv, &m, 84.0, 356.0, col(36, 44, 100), col(86, 98, 160));
    for (x, y, r) in [(560.0, 140.0, 11.0), (780.0, 190.0, 9.0), (660.0, 260.0, 7.0)] {
        sparkle(&mut cv, x, y, r, col(250, 250, 255));
    }
    for (x, y) in [(610.0, 110.0), (720.0, 130.0), (840.0, 120.0), (530.0, 230.0), (850.0, 280.0), (600.0, 330.0), (760.0, 310.0)] {
        ell(&mut cv, x, y, 2.2, 2.2, col(236, 240, 255));
    }
    rect(&mut cv, 684.0, 84.0, 12.0, 272.0, col(246, 240, 230));
    rect(&mut cv, 494.0, 214.0, 392.0, 10.0, col(246, 240, 230));
    rect(&mut cv, 470.0, 370.0, 440.0, 12.0, col(228, 220, 210));
    // カーテン
    poly(&mut cv, &[(430.0, 60.0), (484.0, 60.0), (484.0, 380.0), (430.0, 392.0)], col(204, 170, 160));
    poly(&mut cv, &[(896.0, 60.0), (950.0, 60.0), (950.0, 392.0), (896.0, 380.0)], col(204, 170, 160));
    // 本棚（4 段）
    rect(&mut cv, 40.0, 90.0, 300.0, 400.0, col(150, 112, 84));
    let books = [col(208, 96, 96), col(96, 142, 188), col(232, 196, 96), col(112, 168, 128), col(170, 120, 176), col(236, 232, 220)];
    for row in 0..4 {
        let y = 104.0 + row as f32 * 96.0;
        rect(&mut cv, 52.0, y, 276.0, 84.0, col(122, 90, 68));
        let mut x = 58.0;
        let mut k = row * 2;
        while x < 316.0 {
            let w = [18.0, 26.0, 22.0, 30.0][k % 4];
            let h = [70.0, 62.0, 74.0, 58.0][(k + row) % 4];
            if x + w > 322.0 {
                break;
            }
            rect(&mut cv, x, y + 84.0 - h - 2.0, w, h, books[k % books.len()]);
            x += w + 3.0;
            k += 1;
        }
    }
    // 星図ポスター
    rect(&mut cv, 1000.0, 120.0, 160.0, 220.0, col(40, 54, 110));
    for (x, y) in [(1030.0, 160.0), (1090.0, 190.0), (1060.0, 240.0), (1120.0, 280.0), (1040.0, 300.0)] {
        ell(&mut cv, x, y, 3.0, 3.0, col(250, 240, 200));
    }
    bar(&mut cv, (1030.0, 160.0), (1090.0, 190.0), 1.8, col(150, 170, 220));
    bar(&mut cv, (1090.0, 190.0), (1060.0, 240.0), 1.8, col(150, 170, 220));
    bar(&mut cv, (1060.0, 240.0), (1120.0, 280.0), 1.8, col(150, 170, 220));
    // 望遠鏡（右端、三脚つき）
    let steel = col(78, 96, 122);
    bar(&mut cv, (1210.0, 400.0), (1150.0, 560.0), 9.0, steel);
    bar(&mut cv, (1210.0, 400.0), (1250.0, 560.0), 9.0, steel);
    bar(&mut cv, (1210.0, 400.0), (1200.0, 570.0), 9.0, steel);
    bar(&mut cv, (1244.0, 330.0), (1176.0, 424.0), 38.0, col(226, 230, 238));
    bar(&mut cv, (1250.0, 322.0), (1230.0, 350.0), 44.0, col(96, 116, 150));
    // 天井灯の暖色（床に落ちる 1 枚の明るい楕円）
    path(&mut cv, &Path::ellipse(640.0, 640.0, 360.0, 70.0, 0.0), cola(255, 226, 168, 0.28));
    cv
}
